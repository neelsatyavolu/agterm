#!/usr/bin/env python3
"""Writes site/changelog.html from CHANGELOG.md: every stable release, newest first.

Beta sections are left out, as in stable builds of the app; each stable section already
repeats what its betas shipped.

Usage: scripts/site-changelog.py           (rewrite site/changelog.html)
       scripts/site-changelog.py --check   (exit 1 if it is out of date; release.sh runs this)
"""
import html
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "CHANGELOG.md"
OUTPUT = ROOT / "site" / "changelog.html"

HEADING = re.compile(r"^## (\S+) — (\d{4}-\d{2}-\d{2})\s*$")
BULLET = re.compile(r"^- (?:(Added|Fixed|Changed): )?(.*)$")
MONTHS = ["January", "February", "March", "April", "May", "June", "July",
          "August", "September", "October", "November", "December"]


def parse(text):
    """Returns [(version, date, [(kind, text)])] for stable sections, in file order."""
    releases, current = [], None
    for line in text.splitlines():
        heading = HEADING.match(line)
        if heading:
            version, date = heading.groups()
            current = None if "-beta." in version else (version, date, [])
            if current:
                releases.append(current)
            continue
        bullet = BULLET.match(line)
        if current and bullet:
            current[2].append((bullet.group(1) or "", bullet.group(2)))
    return releases


def inline(text):
    """Escapes text and turns `code` spans into <code>."""
    parts = text.split("`")
    return "".join(f"<code>{html.escape(p)}</code>" if i % 2 else html.escape(p)
                   for i, p in enumerate(parts))


def pretty_date(date):
    year, month, day = date.split("-")
    return f"{MONTHS[int(month) - 1]} {int(day)}, {year}"


def render_release(version, date, items):
    rows = "\n".join(
        f'            <li><span class="cl-kind cl-{kind.lower() or "note"}">{kind}</span>'
        f'<span>{inline(body)}</span></li>'
        for kind, body in items)
    return f"""        <section class="cl-release" id="v{version}" aria-labelledby="v{version}-title">
          <header class="cl-head">
            <h2 id="v{version}-title"><a href="#v{version}">{version}</a></h2>
            <p class="meta"><time datetime="{date}">{pretty_date(date)}</time></p>
          </header>
          <ul class="cl-items">
{rows}
          </ul>
        </section>"""


def render(releases):
    body = "\n\n".join(render_release(*r) for r in releases)
    return f"""<!doctype html>
<!-- Generated by scripts/site-changelog.py from CHANGELOG.md; edit that file, then rerun it. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Changelog · agterm</title>
  <meta name="description" content="What changed in each agterm release.">
  <meta name="theme-color" content="#0E0E0D">
  <link rel="canonical" href="https://agterm.dev/changelog">
  <link rel="icon" type="image/svg+xml" href="/favicon.svg">
  <link rel="preconnect" href="https://fonts.googleapis.com">
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
  <link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Geist:wght@400;500;600&family=Geist+Mono:wght@400;500;600&family=Newsreader:ital,opsz,wght@0,6..72,400;1,6..72,400&display=swap">
  <link rel="stylesheet" href="/styles.css?v=1.2.2">
  <script defer src="https://analytics.n3el.dev/p.js"></script>
</head>
<body>
  <a class="skip" href="#main">Skip to content</a>

  <header class="top">
    <div class="wrap top-row">
      <a class="mark" href="/" aria-label="agterm home"><span class="mark-prompt" aria-hidden="true">&gt;</span>agterm</a>
      <nav aria-label="Sections">
        <a class="nav-gh" href="https://github.com/neelsatyavolu/agterm">GitHub</a>
        <a class="btn btn-ghost btn-sm" href="https://github.com/neelsatyavolu/agterm/releases/latest/download/agterm.zip">Download</a>
      </nav>
    </div>
  </header>

  <main id="main" class="block policy">
    <div class="wrap">
      <header class="sec-head">
        <p class="label">Changelog</p>
        <div>
          <h1 class="policy-title">What's new in agterm</h1>
          <p class="sec-lede">Every release, newest first. agterm updates itself; the same notes appear in its What's New tab.</p>
        </div>
      </header>

      <div class="cl">
{body}
      </div>
    </div>
  </main>

  <footer class="foot">
    <div class="wrap foot-row">
      <a class="mark" href="/" aria-label="agterm home"><span class="mark-prompt" aria-hidden="true">&gt;</span>agterm</a>
      <p class="meta">MIT licensed · <a href="https://github.com/neelsatyavolu/agterm">Source</a> · <a href="https://github.com/neelsatyavolu/agterm/releases">Releases</a> · <a href="/privacy">Privacy</a> · <a href="https://xanom.co">Xanom</a></p>
    </div>
  </footer>
</body>
</html>
"""


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        sys.exit("usage: scripts/site-changelog.py [--check]")
    releases = parse(SOURCE.read_text(encoding="utf-8"))
    if not releases:
        sys.exit("error: CHANGELOG.md has no stable release sections")
    page = render(releases)
    if check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != page:
            sys.exit("error: site/changelog.html is out of date; run scripts/site-changelog.py and commit it")
        return
    OUTPUT.write_text(page, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(releases)} releases)")


if __name__ == "__main__":
    main()
